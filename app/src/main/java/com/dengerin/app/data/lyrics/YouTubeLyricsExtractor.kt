package com.dengerin.app.data.lyrics

import com.dengerin.app.core.youtubeVideoId
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.OkHttpClient
import okhttp3.Request
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.services.youtube.linkHandler.YoutubeSearchQueryHandlerFactory
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamInfoItem
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.util.Locale

private const val YOUTUBE_WATCH_URL = "https://www.youtube.com/watch?v="
private const val CAPTION_USER_AGENT = "Mozilla/5.0 (Linux; Android 13) AppleWebKit/537.36 Chrome/120 Mobile Safari/537.36"
private const val MAX_SEARCH_CANDIDATES = 3
private const val MERGE_WINDOW_MS = 150L

/**
 * Fallback lirik tersinkronisasi dari Closed Captions YouTube lewat NewPipeExtractor.
 *
 * Urutannya hemat kuota: subtitle video yang sedang diputar → satu kali pencarian ringan
 * (`judul + artis + lyrics`) bila video itu tidak punya caption. Pencarian hanya mengambil
 * metadata `StreamInfo`, tidak mengunduh video/audio. Semua caption yang berhasil di-parse
 * dikembalikan sebagai [LyricLine] agar memakai pipeline animasi yang sama dengan LRCLIB.
 */
class YouTubeLyricsExtractor(
    private val client: OkHttpClient,
) {

    suspend fun load(videoId: String, title: String, artist: String): List<LyricLine>? =
        withContext(Dispatchers.IO) {
            val languageHint = Locale.getDefault().language.ifBlank { "id" }

            val direct = runCatching {
                StreamInfo.getInfo(ServiceList.YouTube, YOUTUBE_WATCH_URL + videoId).subtitles
            }.getOrNull().orEmpty()
            bestLines(direct, languageHint)?.let { return@withContext it }

            // Satu pencarian ringan; hanya beberapa kandidat teratas yang dicek subtitlenya.
            val query = "$title$artist lyrics".trim()
            val candidates = runCatching {
                val extractor = ServiceList.YouTube.getSearchExtractor(
                    query,
                    listOf(YoutubeSearchQueryHandlerFactory.MUSIC_SONGS),
                    "",
                )
                extractor.fetchPage()
                extractor.initialPage.items
                    .filterIsInstance<StreamInfoItem>()
                    .map { it.url }
            }.getOrNull().orEmpty()

            for (url in candidates.distinct().take(MAX_SEARCH_CANDIDATES)) {
                if (youtubeVideoId(url) == videoId) continue
                val tracks = runCatching {
                    StreamInfo.getInfo(ServiceList.YouTube, url).subtitles
                }.getOrNull().orEmpty()
                bestLines(tracks, languageHint)?.let { return@withContext it }
            }

            null
        }

    /** Manual lebih utama, lalu bahasa lagu/id/en/ja/ko, baru track pertama yang ada. */
    private fun bestLines(tracks: List<SubtitlesStream>, languageHint: String): List<LyricLine>? {
        if (tracks.isEmpty()) return null
        val ordered = tracks.sortedWith(
            compareBy<SubtitlesStream> { it.isAutoGenerated }
                .thenBy { languageRank(it, languageHint) },
        )
        for (track in ordered) {
            val content = loadContent(track) ?: continue
            val lines = parse(content)
            if (lines.isNotEmpty()) return lines
        }
        return null
    }

    private fun languageRank(track: SubtitlesStream, languageHint: String): Int {
        val tag = (track.languageTag ?: track.locale?.language.orEmpty()).lowercase()
        val base = tag.substringBefore('-')
        return when (base) {
            languageHint.lowercase() -> 0
            "id" -> 1
            "en" -> 2
            "ja" -> 3
            "ko" -> 4
            else -> 5
        }
    }

    private fun loadContent(track: SubtitlesStream): String? {
        val raw = track.content
        if (raw.isBlank()) return null
        if (!raw.startsWith("http", ignoreCase = true)) return raw
        return runCatching {
            client.newCall(
                Request.Builder()
                    .url(raw)
                    .header("User-Agent", CAPTION_USER_AGENT)
                    .build(),
            ).execute().use { response ->
                if (!response.isSuccessful) null else response.body?.string()
            }
        }.getOrNull()
    }

    /**
     * Parser captionYouTube: WebVTT/SRT, TTML, XML/SRV1, dan fmt=json3/SRV3.
     * Semua format dinormalisasi ke timestampMs absolut lalu digabungkan bila
     * fragmen kalimat berdekatan (< 150 ms).
     */
    fun parse(content: String): List<LyricLine> {
        if (content.isBlank()) return emptyList()
        val trimmed = content.trimStart()
        val entries = when {
            trimmed.contains("-->") -> parseTimingLines(content)
            trimmed.startsWith("{") || trimmed.contains("\"tStartMs\"") -> parseJson3(trimmed)
            trimmed.contains("<tt") || trimmed.contains("<p ") -> parseTtml(content)
            trimmed.contains("<transcript") || trimmed.contains("<text ") -> parseSrvXml(content)
            else -> emptyList()
        }
        return mergeFragments(entries)
    }

    private fun parseTimingLines(content: String): List<LyricLine> {
        val entries = mutableListOf<LyricLine>()
        var startMs: Long? = null
        val buffer = mutableListOf<String>()

        fun flush() {
            val at = startMs ?: return
            val text = cleanText(buffer.joinToString(" "))
            if (text.isNotEmpty()) entries += LyricLine(at, text)
            startMs = null
            buffer.clear()
        }

        content.lineSequence().forEach { raw ->
            val line = raw.trim()
            if (line.isEmpty()) {
                flush()
                return@forEach
            }
            if (line.contains("-->")) {
                // YouTube VTT mengulang baris timing yang sama; flush kosong tidak apa-apa.
                flush()
                startMs = parseClock(line.substringBefore("-->").trim())
                return@forEach
            }
            if (startMs != null) buffer += line
        }
        flush()
        return entries
    }

    private fun parseTtml(content: String): List<LyricLine> {
        val entries = mutableListOf<LyricLine>()
        ttmlParagraph.findAll(content).forEach { match ->
            val rawTime = ttmlTimeAttr.find(match.groupValues[1])?.groupValues?.get(1)
            val startMs = rawTime?.let(::parseClock) ?: return@forEach
            val text = cleanText(match.groupValues[2])
            if (text.isNotEmpty()) entries += LyricLine(startMs, text)
        }
        return entries
    }

    private fun parseSrvXml(content: String): List<LyricLine> {
        val entries = mutableListOf<LyricLine>()
        srvTextTag.findAll(content).forEach { match ->
            val rawTime = srvTimeAttr.find(match.groupValues[1])?.groupValues?.get(1)
            val startMs = rawTime?.let(::parseClock) ?: return@forEach
            val text = cleanText(match.groupValues[2])
            if (text.isNotEmpty()) entries += LyricLine(startMs, text)
        }
        return entries
    }

    private fun parseJson3(content: String): List<LyricLine> {
        val entries = mutableListOf<LyricLine>()
        // Event json3 bisa memuat objek `segs` bersarang; pola ini menerima satu level.
        jsonEvent.findAll(content).forEach { eventMatch ->
            val event = eventMatch.value
            val startMs = jsonStart.find(event)?.groupValues?.get(1)?.toLongOrNull()
                ?: return@forEach
            val text = jsonUtf8.findAll(event)
                .map { decodeJsonString(it.groupValues[1]) }
                .toList()
                .joinToString(separator = "")
                .let(::cleanText)
            if (text.isNotEmpty()) entries += LyricLine(startMs, text)
        }
        return entries
    }

    private fun decodeJsonString(value: String): String = buildString {
        var index = 0
        while (index < value.length) {
            if (value[index] != '\\' || index + 1 >= value.length) {
                append(value[index])
                index++
                continue
            }
            when (val escaped = value[index + 1]) {
                'n' -> append('\n')
                'r' -> append('\r')
                't' -> append('\t')
                'u' -> {
                    val hex = value.substring(index + 2, (index + 6).coerceAtMost(value.length))
                    val codePoint = hex.toIntOrNull(16)
                    if (codePoint != null) append(Character.toChars(codePoint))
                    index += 4
                }
                else -> append(escaped)
            }
            index += 2
        }
    }

    private fun mergeFragments(entries: List<LyricLine>): List<LyricLine> {
        val sorted = entries
            .map { it.copy(text = normalizeInstrumental(it.text)) }
            .filter { it.text.isNotEmpty() }
            .sortedBy { it.timestampMs }
        val merged = mutableListOf<LyricLine>()

        for (line in sorted) {
            val lastIndex = merged.lastIndex
            if (lastIndex >= 0) {
                val last = merged[lastIndex]
                val gap = line.timestampMs - last.timestampMs
                if (gap in 0 until MERGE_WINDOW_MS) {
                    val joined = joinText(last.text, line.text)
                    if (joined != last.text) merged[lastIndex] = last.copy(text = joined)
                    continue
                }
            }
            merged += line
        }
        return merged
    }

    private fun joinText(current: String, next: String): String {
        if (current == next || current == INSTRUMENTAL || next == INSTRUMENTAL) return current
        val separator = if (current.endsWith(' ') || next.startsWith(' ')) "" else " "
        return (current + separator + next).replace(WHITESPACE, " ").trim()
    }

    private fun normalizeInstrumental(text: String): String =
        if (instrumentalOnly.matches(text.trim())) INSTRUMENTAL else text

    private fun cleanText(raw: String): String {
        val withoutMarkup = markupTag.replace(raw, " ")
        val decoded = htmlEntity.replace(withoutMarkup) { match ->
            when (val entity = match.value) {
                "&amp;" -> "&"
                "&quot;" -> "\""
                "&apos;" -> "'"
                "&lt;" -> "<"
                "&gt;" -> ">"
                "&nbsp;" -> " "
                else -> decodeNumericEntity(entity)
            }
        }
        return decoded.replace(WHITESPACE, " ").trim()
    }

    private fun decodeNumericEntity(entity: String): String {
        val body = entity.removePrefix("&").removeSuffix(";")
        val codePoint = if (body.startsWith("#x", ignoreCase = true)) {
            body.removePrefix("#x").toIntOrNull(16)
        } else {
            body.removePrefix("#").toIntOrNull()
        } ?: return entity
        return runCatching { String(Character.toChars(codePoint)) }.getOrDefault(entity)
    }

    private fun parseClock(rawValue: String): Long? {
        var value = rawValue.trim().replace(',', '.')
        if (value.endsWith("s", ignoreCase = true)) value = value.dropLast(1)
        if (value.isEmpty()) return null

        return try {
            if (!value.contains(':')) {
                val seconds = value.toDoubleOrNull() ?: return null
                return (seconds * 1000L).toLong()
            }

            val parts = value.split(':')
            var millis = 0L
            for (index in parts.indices) {
                val part = parts[index]
                if (index == parts.lastIndex && part.contains('.')) {
                    val (seconds, fraction) = part.split('.', limit = 2)
                    millis += seconds.toLong() * 1_000L + fractionToMillis(fraction)
                } else if (index == parts.lastIndex && parts.size >= 3 && part.length == 2) {
                    // Format LRC HH:MM:SS:cc memakai centisecond, bukan detik.
                    millis += part.toLong() * 10L
                } else {
                    val multiplier = when (parts.lastIndex - index) {
                        1 -> 60_000L
                        2 -> 3_600_000L
                        else -> 1_000L
                    }
                    millis += part.toLong() * multiplier
                }
            }
            millis
        } catch (_: NumberFormatException) {
            null
        }
    }

    private fun fractionToMillis(fraction: String): Long = when {
        fraction.isEmpty() -> 0L
        fraction.length >= 3 -> fraction.take(3).toLong()
        else -> fraction.padEnd(3, '0').toLong()
    }

    private companion object {
        const val INSTRUMENTAL = "♪"
        val WHITESPACE = Regex("""\s+""")
        val markupTag = Regex("""<[^>]*>""")
        val htmlEntity = Regex("""&(?:amp|quot|apos|lt|gt|nbsp|#x[0-9a-fA-F]+|#\d+);""")
        val instrumentalOnly = Regex(
            """^[\[(]\s*(?:musik|music|instrumental|instrumen)\s*[\])]$""",
            RegexOption.IGNORE_CASE,
        )
        val ttmlParagraph = Regex("""<p\b([^>]*)>(.*?)</p>""", RegexOption.DOT_MATCHES_ALL)
        val ttmlTimeAttr = Regex("""(?:begin|start)\s*=\s*["']([^"']+)["']""")
        val srvTextTag = Regex("""<text\b([^>]*)>(.*?)</text>""", RegexOption.DOT_MATCHES_ALL)
        val srvTimeAttr = Regex("""(?:start|startTime|begin)\s*=\s*["']([^"']+)["']""")
        val jsonEvent = Regex("""\{(?:[^{}]|\{[^{}]*\})*\}""", RegexOption.DOT_MATCHES_ALL)
        val jsonStart = Regex("\"tStartMs\"\\s*:\\s*(\\d+)")
        val jsonUtf8 = Regex(""""utf8"\s*:\s*"((?:\\.|[^"\\])*)"""")
    }
}
